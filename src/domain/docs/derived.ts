// A file fx derives into the workspace root announces itself on its first
// line, so fx can tell its own output from a person's file and never
// replace the latter.

const PREFIX = '<!-- fx:derived ';

export const DERIVED_GUIDE = 'AGENTS.md';

// Claude Code reads the guide itself, and reads this file in its place whenever it
// exists. fx therefore derives none: a marked copy is the pointer earlier versions
// wrote and is removed, and any other belongs to the person.
export const CLAUDE_GUIDE = 'CLAUDE.md';

export const marker = (origin: string): string =>
  `${PREFIX}from ${origin}; regenerated by fx sync, edit the origin instead -->`;

export const isDerived = (text: string): boolean => text.startsWith(PREFIX);

export const derive = (text: string, origin: string): string => `${marker(origin)}\n${text}`;
