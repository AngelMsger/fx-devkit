// Render a schema 2 candidate with verified provider bindings and review notes for unresolved inference.

import type { YAMLMap, YAMLSeq } from 'yaml';
import { Document } from 'yaml';

import type { FoldedManifest } from './fold.js';

export function renderManifest(folded: FoldedManifest): string {
  const doc = new Document({
    schema_version: 2,
    providers:
      folded.provider === undefined
        ? {}
        : {
            'code-host': {
              provider: folded.provider.provider,
              vars: { host: folded.provider.host },
            },
          },
    defaults: folded.defaults,
    projects: Object.fromEntries(folded.projects.map((p) => [p, { label: p, contact: '' }])),
    repos: [],
  });
  doc.commentBefore =
    ' Generated by `fx manifest import`. Review the entries marked `review:`, delete what the\n team should not share, then commit. `fx manifest lint` reports what is left to tidy.';
  const repos = doc.get('repos') as YAMLSeq<YAMLMap>;
  for (const repo of folded.repos) {
    const { review, ...fields } = repo;
    const node = doc.createNode(fields) as YAMLMap;
    node.flow = false;
    if (review.length > 0) node.commentBefore = review.map((r) => ` review: ${r}`).join('\n');
    repos.add(node);
  }
  return doc.toString({ lineWidth: 0 });
}
