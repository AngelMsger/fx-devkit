// The Go workspace file fx keeps at the root when the manifest asks for one: every
// Go module checked out there, at the newest `go` version any of them requires, so
// each module builds against its siblings' checkouts. The file announces itself on
// its first line, so fx can tell its own go.work from a person's and never replace
// the latter.

export const GO_WORK = 'go.work';
export const GO_WORK_SUM = 'go.work.sum';

const PREFIX = '// fx:derived ';

export interface GoModule {
  // Forward-slash path from the root to the module's directory.
  readonly path: string;
  // The module's `go` directive; undefined when its go.mod declares none.
  readonly go: string | undefined;
}

export const isDerivedGoWork = (text: string): boolean => text.startsWith(PREFIX);

export function goDirective(goMod: string): string | undefined {
  return /^go[ \t]+([^\s/]+)/m.exec(goMod)?.[1];
}

// Null when no module is checked out: an empty go.work would only break builds.
export function renderGoWork(modules: readonly GoModule[]): string | null {
  if (modules.length === 0) return null;
  const go = modules.reduce<string | undefined>(
    (newest, module) => newer(newest, module.go),
    undefined,
  );
  const uses = modules.map((module) => `./${module.path}`).sort();
  return [
    `${PREFIX}from the checked-out Go modules; regenerated by fx sync, do not edit`,
    ...(go === undefined ? [] : ['', `go ${go}`]),
    '',
    'use (',
    ...uses.map((use) => `\t${use}`),
    ')',
    '',
  ].join('\n');
}

// Go versions are not semver: `1.21` names the language, `1.21rc1` a release
// candidate and `1.21.0` its first release. Only the numbers decide here; the
// first spelling of an equal version is kept.
function newer(a: string | undefined, b: string | undefined): string | undefined {
  if (a === undefined) return b;
  if (b === undefined) return a;
  const [x, y] = [numbers(a), numbers(b)];
  for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return (x[i] ?? 0) > (y[i] ?? 0) ? a : b;
  return a;
}

function numbers(version: string): number[] {
  const match = /^(\d+)(?:\.(\d+))?(?:\.(\d+))?/.exec(version);
  return [1, 2, 3].map((group) => Number(match?.[group] ?? 0));
}
