import { describe, expect, it } from 'vitest';

import {
  goDirective,
  isDerivedGoWork,
  renderGoWork,
} from '../../../../src/domain/workspace/go-work.js';

describe('go.work', () => {
  it('reads the go directive and ignores comments, toolchain lines and its absence', () => {
    expect(
      goDirective('module example.com/api\n\ngo 1.24.0 // floor\n\ntoolchain go1.25.1\n'),
    ).toBe('1.24.0');
    expect(goDirective('module example.com/api\n\ngo\t1.22\n')).toBe('1.22');
    expect(goDirective('module example.com/api\n// go 1.30\n')).toBeUndefined();
  });

  it('uses every module in path order at the newest go version any of them requires', () => {
    const text = renderGoWork([
      { path: 'src/web', go: '1.24.0' },
      { path: 'src/api', go: '1.25.0' },
      { path: 'src/kit', go: '1.9' },
      { path: 'src/old', go: undefined },
    ]);
    expect(text).toBe(
      [
        '// fx:derived from the checked-out Go modules; regenerated by fx sync, do not edit',
        '',
        'go 1.25.0',
        '',
        'use (',
        '\t./src/api',
        '\t./src/kit',
        '\t./src/old',
        '\t./src/web',
        ')',
        '',
      ].join('\n'),
    );
    expect(isDerivedGoWork(text!)).toBe(true);
  });

  it('compares go versions by their numbers, so 1.10 is newer than 1.9', () => {
    expect(
      renderGoWork([
        { path: 'a', go: '1.9.7' },
        { path: 'b', go: '1.10' },
      ]),
    ).toContain('\ngo 1.10\n');
  });

  it('writes no go line when no module declares one, and nothing without a module', () => {
    expect(renderGoWork([{ path: 'api', go: undefined }])).not.toContain('\ngo ');
    expect(renderGoWork([])).toBeNull();
    expect(isDerivedGoWork('go 1.25.0\n\nuse ./api\n')).toBe(false);
  });
});
